import type { Level3D } from "./levelTypes";

const heights = (rows: number[][]): { x: number; z: number; height: number }[] =>
  rows.flatMap((row, z) => row.map((height, x) => ({ x, z, height })));

const make = (id: string, name: string, rows: number[][], playerStart: { x: number; z: number }, goal: { x: number; z: number }): Level3D => ({
  id, name, width: rows[0].length, depth: rows.length, maxHeight: Math.max(...rows.flat()), cells: heights(rows), playerStart, goal,
});

const flat = (h: number, width = 7, depth = 7) => Array.from({ length: depth }, () => Array(width).fill(h));

